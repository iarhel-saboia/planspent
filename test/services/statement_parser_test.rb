require "test_helper"

class StatementParserTest < ActiveSupport::TestCase
  def upload(content, filename)
    Rack::Test::UploadedFile.new(StringIO.new(content.b), "application/octet-stream", original_filename: filename)
  end

  def parse(content, filename = "extrato.csv")
    StatementParser.call(upload(content, filename)).map { |t| [ t.occurred_on.iso8601, t.description, t.amount.to_s("F"), t.kind ] }
  end

  test "reads OFX 1.x (SGML, Windows-1252) with signed amounts" do
    assert_equal [
      [ "2026-09-05", "Salário ACME", "4200.0", "credit" ],
      [ "2026-09-06", "DROGASIL 123 & CIA", "35.9", "debit" ],
      [ "2026-09-07", "Aluguel setembro", "1500.0", "debit" ]
    ], parse(file_fixture("extrato.ofx").binread, "extrato.ofx")
  end

  test "reads OFX 2.x (XML)" do
    ofx = <<~XML
      <?xml version="1.0" encoding="UTF-8"?><?OFX OFXHEADER="200" VERSION="220"?>
      <OFX><CREDITCARDMSGSRSV1><CCSTMTTRNRS><CCSTMTRS><BANKTRANLIST>
      <STMTTRN><TRNTYPE>DEBIT</TRNTYPE><DTPOSTED>20261002</DTPOSTED><TRNAMT>-59.90</TRNAMT><MEMO>Netflix.com</MEMO></STMTTRN>
      </BANKTRANLIST></CCSTMTRS></CCSTMTTRNRS></CREDITCARDMSGSRSV1></OFX>
    XML
    assert_equal [ [ "2026-10-02", "Netflix.com", "59.9", "debit" ] ], parse(ofx, "fatura.ofx")
  end

  test "reads a signed account CSV (Nubank conta)" do
    csv = <<~CSV
      Data,Valor,Identificador,Descrição
      01/10/2026,-12.50,abc,Compra no débito - Padaria Central
      02/10/2026,1500.00,def,Transferência recebida pelo Pix - FULANO
    CSV
    assert_equal [
      [ "2026-10-01", "Compra no débito - Padaria Central", "12.5", "debit" ],
      [ "2026-10-02", "Transferência recebida pelo Pix - FULANO", "1500.0", "credit" ]
    ], parse(csv)
  end

  test "reads a credit card CSV, where purchases are positive" do
    csv = <<~CSV
      date,title,amount
      2026-10-03,Uber *Trip,23.40
      2026-10-04,iFood,58.00
      2026-10-10,Pagamento recebido,-500.00
    CSV
    assert_equal %w[debit debit credit], parse(csv).map(&:last)
  end

  test "reads a ';' CSV with a preamble and separate crédito/débito columns, skipping balance lines" do
    csv = <<~CSV
      Extrato de conta corrente;;;
      Agência 0001 Conta 12345-6;;;
      Data Lançamento;Histórico;Crédito (R$);Débito (R$)
      30/09/2026;SALDO ANTERIOR;1.000,00;
      01/10/2026;PIX RECEBIDO JOAO;1.234,56;
      02/10/2026;CONTA DE LUZ ENEL;;-210,30
    CSV
    assert_equal [
      [ "2026-10-01", "PIX RECEBIDO JOAO", "1234.56", "credit" ],
      [ "2026-10-02", "CONTA DE LUZ ENEL", "210.3", "debit" ]
    ], parse(csv.encode("Windows-1252"))
  end

  test "guesses the columns of a CSV without header" do
    csv = "05/10/26;MERCADO LIVRE*LOJA;-89,90\n06/10/26;ESTORNO MERCADO LIVRE;89,90\n"
    assert_equal [
      [ "2026-10-05", "MERCADO LIVRE*LOJA", "89.9", "debit" ],
      [ "2026-10-06", "ESTORNO MERCADO LIVRE", "89.9", "credit" ]
    ], parse(csv)
  end

  test "reads a PDF generated by the bank, ignoring the balance column" do
    assert_equal [
      [ "2026-09-05", "Salário ACME", "4200.0", "credit" ],
      [ "2026-09-06", "DROGASIL 123", "35.9", "debit" ],
      [ "2026-09-07", "Aluguel setembro", "1500.0", "debit" ]
    ], parse(file_fixture("extrato.pdf").binread, "extrato.pdf")
  end

  test "reads credit card bill text, where only payments and refunds are credits" do
    text = <<~TEXT
      Fatura de novembro 2026 - vencimento 15/11/2026
      05 OUT IFOOD *RESTAURANTE 58,90
      28 dez. UBER *TRIP R$ 23,40
      01 MARIA LUIZA 10,00
      10 NOV Pagamento recebido −500,00
      12 NOV Estorno Loja 9,90
      Total da fatura 1.234,56
    TEXT
    rows = StatementParser::Text.new(text).transactions.map { |t| [ t.occurred_on.iso8601, t.description, t.kind ] }
    assert_equal [
      [ "2026-10-05", "IFOOD *RESTAURANTE", "debit" ],
      [ "2025-12-28", "UBER *TRIP", "debit" ],
      [ "2026-11-10", "Pagamento recebido", "credit" ],
      [ "2026-11-12", "Estorno Loja", "credit" ]
    ], rows
  end

  test "explicit + and - signs decide money in and out, whatever the description" do
    text = <<~TEXT
      Extrato de outubro 2026
      01/10 PAGAMENTO FATURA CARTAO - R$ 1.200,00
      02/10 TRANSFERENCIA PIX JOAO + R$ 300,00
      03/10 PIX JOSE + 50,00
      04/10 ESTORNO TARIFA R$ +9,90
      05/10 PIX ENVIADO MARIA -80,00
      06/10 PAGAMENTO BOLETO (-) R$ 45,00
      07/10 PIX RECEBIDO ANA (+) R$ 20,00
    TEXT
    rows = StatementParser::Text.new(text).transactions.map { |t| [ t.description, t.amount.to_s("F"), t.kind ] }
    assert_equal [
      [ "PAGAMENTO FATURA CARTAO", "1200.0", "debit" ],
      [ "TRANSFERENCIA PIX JOAO", "300.0", "credit" ],
      [ "PIX JOSE", "50.0", "credit" ],
      [ "ESTORNO TARIFA", "9.9", "credit" ],
      [ "PIX ENVIADO MARIA", "80.0", "debit" ],
      [ "PAGAMENTO BOLETO", "45.0", "debit" ],
      [ "PIX RECEBIDO ANA", "20.0", "credit" ]
    ], rows

    csv = "Data;Descrição;Valor\n01/10/2026;Pagamento fatura;-1.200,00\n02/10/2026;Pix recebido;+300,00\n03/10/2026;Pix recebido;+50,00\n"
    assert_equal %w[debit credit credit], parse(csv).map(&:last)
  end

  test "reads Banco do Brasil statements: trailing (+)/(-), descriptions split over lines, lot numbers" do
    text = <<~TEXT
      Extrato de Conta Corrente
      Período: 01 a 30/09/2026                  Agência: 0000-0  Conta: 00000-0
        Dia           Lote       Documento               Histórico                                     Valor
        28/08/2026                                       Saldo Anterior                             14,78 (-)
                                                         Pix - Recebido
        01/09/2026    14397      12017514228851          01/09 20:17 12345678901 FULANO DE TAL    1.351,00 (+)


        01/09/2026    13105      90101                   Pix - Enviado                             555,08 (-)
                                                         01/09 20:22 PLANO DE SAUDE XYZ
                                                         Cobrança de Juros
        01/09/2026    13601      511058916                                                           0,15 (-)
                                                         Juros Saldo Devedor Conta
                                                         Saldo do dia                              694,87 (+)
                                                         Pix - Enviado
        02/09/2026    13105      90202                   02/09 10:21 CICLANA DE CARVALHO            17,50 (-)

                                                         SOARES
        02/09/2026    13105      90203                   Pix - Enviado                             400,00 (-)
                                                         02/09 10:34 BELTRANO SILVA
        08/09/2026    99020      780317800979503         Pagto cartão crédito                      157,00 (-)
        30/09/2026                                       S A L D O                                  30,82 (+)
        Informações Adicionais
      \f
      Extrato de Conta Corrente
        Valor Total Devido                                                     325,87          -
    TEXT
    rows = StatementParser::Text.new(text).transactions.map { |t| [ t.occurred_on.iso8601, t.description, t.amount.to_s("F"), t.kind ] }
    assert_equal [
      [ "2026-09-01", "Pix - Recebido FULANO DE TAL", "1351.0", "credit" ],
      [ "2026-09-01", "Pix - Enviado PLANO DE SAUDE XYZ", "555.08", "debit" ],
      [ "2026-09-01", "Cobrança de Juros Juros Saldo Devedor Conta", "0.15", "debit" ],
      [ "2026-09-02", "Pix - Enviado CICLANA DE CARVALHO SOARES", "17.5", "debit" ],
      [ "2026-09-02", "Pix - Enviado BELTRANO SILVA", "400.0", "debit" ],
      [ "2026-09-08", "Pagto cartão crédito", "157.0", "debit" ]
    ], rows
  end

  test "images need Tesseract (or readable text)" do
    assert_raises(StatementParser::Error) { parse("\x89PNG\r\n\x1A\nnot really an image", "foto.png") }
  end

  test "rejects unsupported files and CSVs without date or amount" do
    error = assert_raises(StatementParser::Error) { parse("PK\x03\x04", "extrato.docx") }
    assert_match "OFX, CSV, PDF ou imagem", error.message
    assert_raises(StatementParser::Error) { parse("%PDF-1.7 broken", "extrato.pdf") }

    assert_raises(StatementParser::Error) { parse("nome,email\nAna,ana@x.com\n") }
  end

  test "parses Brazilian and international amounts" do
    {
      "1.234,56" => "1234.56", "-1234.56" => "-1234.56", "R$ 1.234,56 D" => "-1234.56",
      "(12,50)" => "-12.5", "12,50-" => "-12.5", "1.234" => "1234.0", "1,234.50" => "1234.5"
    }.each { |text, expected| assert_equal expected, StatementParser.parse_amount(text).to_s("F"), text }
  end
end
